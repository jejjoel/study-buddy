create table if not exists public.schedules (
  id             bigint generated by default as identity primary key,
  user_id        bigint not null references public.users(id) on delete cascade,
  discussion_id  bigint references public.discussions(id) on delete cascade,
  title          varchar(255) not null,
  interest_field varchar(255),
  room_code      varchar(50),
  scheduled_at   timestamp without time zone not null,
  created_at     timestamptz default now(),
  updated_at     timestamptz default now()
);

create index if not exists schedules_user_id_idx on public.schedules (user_id);
create index if not exists schedules_discussion_id_idx on public.schedules (discussion_id);
create unique index if not exists schedules_user_discussion_uidx
  on public.schedules (user_id, discussion_id)
  where discussion_id is not null;

alter table public.schedules enable row level security;

create policy "schedules_select_own"
  on public.schedules for select
  to authenticated
  using (user_id = (select public.current_user_id()));

create policy "schedules_insert_own"
  on public.schedules for insert
  to authenticated
  with check (user_id = (select public.current_user_id()));

create policy "schedules_update_own"
  on public.schedules for update
  to authenticated
  using (user_id = (select public.current_user_id()))
  with check (user_id = (select public.current_user_id()));

create policy "schedules_delete_own"
  on public.schedules for delete
  to authenticated
  using (user_id = (select public.current_user_id()));

