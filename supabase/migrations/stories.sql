-- =====================================================
-- STORIES & STORAGE BUCKETS (stories, avatars)
-- Project: study-buddy-database
-- =====================================================

create table if not exists public.stories (
  id          bigint generated by default as identity primary key,
  user_id     bigint not null references public.users(id) on delete cascade,
  media_url   text not null,
  media_path  text not null,
  caption     text,
  created_at  timestamptz not null default now(),
  expires_at  timestamptz not null default (now() + interval '24 hours')
);

create index if not exists stories_user_id_idx    on public.stories (user_id);
create index if not exists stories_expires_at_idx on public.stories (expires_at);

alter table public.stories enable row level security;

create policy "stories_select_active"
  on public.stories for select
  to authenticated
  using (expires_at > now());

create policy "stories_insert_own"
  on public.stories for insert
  to authenticated
  with check (user_id = (select public.current_user_id()));

create policy "stories_delete_own"
  on public.stories for delete
  to authenticated
  using (user_id = (select public.current_user_id()));

-- Storage Buckets: stories & avatars
insert into storage.buckets (id, name, public)
values
  ('stories', 'stories', true),
  ('avatars', 'avatars', true)
on conflict (id) do nothing;

create policy "stories_storage_read"
  on storage.objects for select
  using (bucket_id = 'stories');

create policy "stories_storage_insert_own"
  on storage.objects for insert
  to authenticated
  with check (
    bucket_id = 'stories'
    and (storage.foldername(name))[1] = (select public.current_user_id())::text
  );

create policy "stories_storage_update_own"
  on storage.objects for update
  to authenticated
  using (
    bucket_id = 'stories'
    and (storage.foldername(name))[1] = (select public.current_user_id())::text
  )
  with check (
    bucket_id = 'stories'
    and (storage.foldername(name))[1] = (select public.current_user_id())::text
  );

create policy "stories_storage_delete_own"
  on storage.objects for delete
  to authenticated
  using (
    bucket_id = 'stories'
    and (storage.foldername(name))[1] = (select public.current_user_id())::text
  );

create policy "avatars_storage_read"
  on storage.objects for select
  using (bucket_id = 'avatars');

create policy "avatars_storage_insert_own"
  on storage.objects for insert
  to authenticated
  with check (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

create policy "avatars_storage_update_own"
  on storage.objects for update
  to authenticated
  using (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  )
  with check (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

create policy "avatars_storage_delete_own"
  on storage.objects for delete
  to authenticated
  using (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

