-- =====================================================
-- USERS & AUTH SYNCHRONIZATION
-- Project: study-buddy-database
-- =====================================================

create extension if not exists pgcrypto with schema extensions;

create table if not exists public.users (
  id            bigint generated by default as identity primary key,
  firebase_uid  varchar(255) not null unique,
  name          varchar(255) not null,
  email         varchar(255) not null unique,
  phone_number  varchar(50),
  phone         text,
  avatar_url    varchar(500),
  genre         varchar(50),
  semester      varchar(50),
  faculty       varchar(255),
  study_program varchar(255),
  major         varchar(255),
  university    varchar(255),
  gpa           numeric(3, 2) check (gpa is null or (gpa >= 0 and gpa <= 4)),
  interests     text[] default '{}'::text[],
  role          varchar(50) not null default 'student'
                check (role in ('student', 'mentor', 'admin')),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create index if not exists users_lower_email_idx on public.users (lower(email));
create index if not exists users_name_idx on public.users (name);

-- Helper: id baris public.users milik akun yang sedang login
create or replace function public.current_user_id()
returns bigint
language sql
stable
security invoker
set search_path = public
as $$
  select id
  from public.users
  where firebase_uid = (select auth.uid())::text
     or lower(email) = lower((select auth.jwt()) ->> 'email')
  order by (firebase_uid = (select auth.uid())::text) desc
  limit 1;
$$;

grant execute on function public.current_user_id() to authenticated;

-- Trigger otomatis sinkronisasi auth.users -> public.users
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.users
  set firebase_uid = new.id::text,
      email = coalesce(new.email, email),
      updated_at = now()
  where lower(email) = lower(new.email)
     or firebase_uid = new.id::text;

  if not found then
    insert into public.users (firebase_uid, name, email, role, created_at, updated_at)
    values (
      new.id::text,
      coalesce(nullif(btrim(new.raw_user_meta_data ->> 'name'), ''), split_part(new.email, '@', 1)),
      new.email,
      'student',
      now(),
      now()
    )
    on conflict (firebase_uid) do nothing;
  end if;

  return new;
end;
$$;

create or replace trigger on_auth_user_created
  after insert or update of email on auth.users
  for each row execute function public.handle_new_auth_user();

alter table public.users enable row level security;

create policy "users_select_authenticated"
  on public.users for select
  to authenticated
  using (true);

create policy "users_insert_own"
  on public.users for insert
  to authenticated
  with check (
    firebase_uid = (select auth.uid())::text
    or lower(email) = lower((select auth.jwt()) ->> 'email')
  );

create policy "users_update_own"
  on public.users for update
  to authenticated
  using (
    firebase_uid = (select auth.uid())::text
    or id = (select public.current_user_id())
  )
  with check (
    firebase_uid = (select auth.uid())::text
    or id = (select public.current_user_id())
  );

