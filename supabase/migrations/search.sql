-- Project: study-buddy-database
-- =====================================================

create table if not exists public.friends (
  id          bigint generated by default as identity primary key,
  user_id     bigint not null references public.users(id) on delete cascade,
  friend_id   bigint not null references public.users(id) on delete cascade,
  created_at  timestamptz not null default now(),
  unique (user_id, friend_id),
  check (user_id <> friend_id)
);

create index if not exists friends_user_id_idx on public.friends (user_id);
create index if not exists friends_friend_id_idx on public.friends (friend_id);

alter table public.friends enable row level security;

create policy "friends_select_own"
  on public.friends for select
  to authenticated
  using (user_id = (select public.current_user_id()));

create policy "friends_insert_own"
  on public.friends for insert
  to authenticated
  with check (user_id = (select public.current_user_id()));

create policy "friends_delete_own"
  on public.friends for delete
  to authenticated
  using (user_id = (select public.current_user_id()));

