create table if not exists public.chat_groups (
  id         integer generated by default as identity primary key,
  name       text not null,
  avatar_url text,
  created_at timestamptz not null default timezone('utc'::text, now())
);

create table if not exists public.chat_group_members (
  id        integer generated by default as identity primary key,
  group_id  integer not null references public.chat_groups(id) on delete cascade,
  user_id   bigint not null references public.users(id) on delete cascade,
  joined_at timestamptz not null default timezone('utc'::text, now()),
  unique (group_id, user_id)
);

create index if not exists chat_group_members_user_idx on public.chat_group_members (user_id);
create index if not exists chat_group_members_group_idx on public.chat_group_members (group_id);

create table if not exists public.chat_messages (
  id          bigint generated by default as identity primary key,
  sender_id   bigint not null references public.users(id) on delete cascade,
  receiver_id bigint references public.users(id) on delete cascade,
  group_id    integer references public.chat_groups(id) on delete cascade,
  text        text not null check (char_length(text) between 1 and 2000),
  created_at  timestamptz not null default now(),
  constraint chat_messages_self_check check (receiver_id is null or sender_id <> receiver_id),
  constraint chat_messages_target_check check (
    (receiver_id is not null and group_id is null) or
    (receiver_id is null and group_id is not null)
  )
);

create index if not exists chat_messages_pair_idx
  on public.chat_messages (sender_id, receiver_id, created_at);
create index if not exists chat_messages_receiver_idx
  on public.chat_messages (receiver_id, created_at);
create index if not exists chat_messages_group_idx
  on public.chat_messages (group_id, created_at);

alter table public.chat_groups enable row level security;
alter table public.chat_group_members enable row level security;
alter table public.chat_messages enable row level security;

create policy "chat_groups_select_all"
  on public.chat_groups for select
  to authenticated
  using (true);

create policy "chat_groups_insert_authenticated"
  on public.chat_groups for insert
  to authenticated
  with check ((select auth.uid()) is not null);

create policy "chat_group_members_select_all"
  on public.chat_group_members for select
  to authenticated
  using (true);

create policy "chat_group_members_insert_own"
  on public.chat_group_members for insert
  to authenticated
  with check (user_id = (select public.current_user_id()));

create policy "chat_group_members_delete_own"
  on public.chat_group_members for delete
  to authenticated
  using (user_id = (select public.current_user_id()));

create policy "chat_messages_select_accessible"
  on public.chat_messages for select
  to authenticated
  using (
    sender_id = (select public.current_user_id())
    or receiver_id = (select public.current_user_id())
    or group_id is not null
  );

create policy "chat_messages_insert_own"
  on public.chat_messages for insert
  to authenticated
  with check (sender_id = (select public.current_user_id()));

